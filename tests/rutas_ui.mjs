import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const js=readFileSync(new URL('../public/assets/app.js',import.meta.url),'utf8');
const section=js.slice(js.indexOf('const slugs='),js.indexOf('const days=['));
const sandbox={history:{calls:[],pushState(...a){this.calls.push(['push',a[2]]);},replaceState(...a){this.calls.push(['replace',a[2]]);}},location:{pathname:'/administrador/horarios'}};
vm.createContext(sandbox);
vm.runInContext("const roles={paciente:{},recepcionista:{},medico:{},administrador:{}};"+section+";this.helpers={pageUrl,parsePageUrl,syncPageUrl}",sandbox);
const {pageUrl,parsePageUrl,syncPageUrl}=sandbox.helpers;
assert.equal(pageUrl('administrador','schedules'),'/administrador/horarios');
assert.equal(pageUrl('administrador','doctors'),'/administrador/medicos');
assert.equal(pageUrl('paciente','appointments'),'/paciente/citas');
assert.equal(parsePageUrl('/administrador/Medicos').view,'doctors');
assert.equal(parsePageUrl('/administrador/horarios').role,'administrador');
assert.equal(parsePageUrl('/administrador/horarios').valid,true);
assert.equal(parsePageUrl('/paciente/historias-clinicas').view,'records');
assert.equal(parsePageUrl('/administrador/loquesea').valid,false);
assert.equal(parsePageUrl('/administrador/horarios/extra').valid,false);
syncPageUrl('administrador','doctors');
assert.equal(sandbox.history.calls.at(-1)[1],'/administrador/medicos');
console.log('OK: direcciones independientes, segmentos y navegación.');
